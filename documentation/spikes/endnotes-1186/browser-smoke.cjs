const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const evidence = path.resolve(__dirname, '../../review-evidence/endnotes-editor-1186');
(async () => {
 const chrome = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || (process.platform === 'darwin' ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' : undefined);
 const browser = await chromium.launch({headless:true,...(chrome ? {executablePath:chrome} : {})});
 try {
  const page = await browser.newPage({viewport:{width:1440,height:1150}});
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8976/documentation/spikes/endnotes-1186/');
  await page.locator('#paragraph-preview').waitFor();
  await page.evaluate(()=>document.fonts.ready);
  await page.locator('#place').click();
  assert.match(await page.locator('#status').textContent(),/Enter citation text/);
  await page.locator('#citation').fill('First synthetic citation.'); await page.locator('#place').click();
  assert.equal(await page.locator('#preview ol li').count(),1);
  await page.locator('#note').selectOption('1'); await page.locator('#block').selectOption('purpose-2'); await page.locator('#place').click();
  assert.equal(await page.locator('#preview sup a').count(),2);
  assert.equal(await page.locator('#endnote-1 a').count(),2);
  await page.locator('#note').selectOption(''); await page.locator('#citation').fill('Second synthetic citation.'); await page.locator('#place').click();
  await page.locator('#note').selectOption('2'); await page.locator('#up').click();
  assert.equal(await page.locator('#endnote-ref-1').textContent(),'[2]');
  await page.locator('#citation').fill('Updated second citation.'); await page.locator('#edit').click();
  assert.match(await page.locator('#endnote-2').textContent(),/Updated second citation/);
  page.once('dialog',d=>d.dismiss()); await page.locator('#delete').click();
  assert.equal(await page.locator('#preview ol li').count(),2);
  page.once('dialog',d=>d.accept()); await page.locator('#delete').click();
  assert.equal(await page.locator('#preview ol li').count(),1);
  assert.equal(await page.locator('#endnote-ref-1').textContent(),'[1]');
  fs.mkdirSync(evidence,{recursive:true});
  await page.screenshot({path:evidence+'/paragraph-placement.png',fullPage:true});
  await page.locator('#block').selectOption('purpose-1'); await page.locator('summary').filter({hasText:'Test an edit'}).click();
  await page.locator('#changed-text').fill('An edited synthetic paragraph.'); await page.locator('#change-text').click();
  assert.match(await page.locator('#issues').textContent(),/text changed/);
  assert.match(await page.locator('#html-output').textContent(),/Unavailable/);
  await page.screenshot({path:evidence+'/stale-reference.png',fullPage:true});
  await page.locator('#relocate').selectOption('1'); await page.locator('#replace-position').click();
  assert.equal(await page.locator('#issues li').count(),0);
  await page.locator('label[for="cursor-mode"]').click(); await page.locator('#block').selectOption('reporting-1');
  await page.locator('#cursor-text').focus(); await page.keyboard.press('ControlOrMeta+A'); await page.keyboard.press('ArrowLeft');
  for(let i=0;i<10;i++) await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('#cursor-text').evaluate(e=>e.selectionStart),10);
  await page.locator('#note').selectOption('1');
  // Changing citation controls resets the cursor preview; position after selection.
  await page.locator('#cursor-text').focus(); await page.keyboard.press('ControlOrMeta+A'); await page.keyboard.press('ArrowLeft');
  for(let i=0;i<10;i++) await page.keyboard.press('ArrowRight');
  await page.locator('#place').click();
  assert.equal(await page.locator('#preview sup a').count(),3);
  await page.screenshot({path:evidence+'/cursor-placement.png',fullPage:true});
  const fonts = await page.locator('h1').evaluate(e=>({family:getComputedStyle(e).fontFamily,weight:getComputedStyle(e).fontWeight}));
  const session = await page.context().newCDPSession(page);
  await session.send('DOM.enable'); await session.send('CSS.enable');
  const doc = await session.send('DOM.getDocument');
  const heading = await session.send('DOM.querySelector',{nodeId:doc.root.nodeId,selector:'h1'});
  fonts.rendered = (await session.send('CSS.getPlatformFontsForNode',{nodeId:heading.nodeId})).fonts;
  assert.ok(fonts.rendered.some(f=>f.isCustomFont && /Merriweather/i.test(f.familyName)));
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:evidence+'/mobile.png'});
  await page.locator('#preview').scrollIntoViewIfNeeded();
  await page.screenshot({path:evidence+'/mobile-preview.png'});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:['empty citation','paragraph insertion','repeated references/backlinks','reorder labels','edit citation','delete cancel/confirm','stale text blocks output','explicit relocation','keyboard cursor placement','390px layout','no JS exceptions'],fonts}));
 } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
